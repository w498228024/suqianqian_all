def expand_content(skill, category):
    """根据分类和原始内容生成扩写版本"""
    title = skill["title"]
    desc = skill["desc"]
    content = skill["content"]
    
    # 获取分类对应的扩写模块
    modules = CATEGORY_MODULES.get(category, DEFAULT_MODULES)
    sections = modules["sections"]
    
    # 如果原始内容已经有一些结构，在其后追加
    expanded = content.rstrip()
    
    # 检查原始内容是否已有某些章节，避免重复
    for section in sections:
        # 提取章节标题（## 后面的文字）
        header_match = re.search(r'##\s+(.+)', section.strip())
        if header_match:
            header = header_match.group(1).strip()
            if header in expanded:
                continue  # 已有该章节，跳过
        expanded += section
    
    return expanded


def main():
    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()
    
    # 获取所有需要扩写的 skill
    cur.execute("""
        SELECT id, title, desc, content, category, sub_category 
        FROM skills 
        WHERE length(content) < 400
    """)
    rows = cur.fetchall()
    
    print(f"需要扩写: {len(rows)} 条")
    
    updated = 0
    for row in rows:
        skill_id, title, desc, content, category, sub_category = row
        skill = {"title": title, "desc": desc, "content": content}
        
        expanded = expand_content(skill, category)
        
        # 确保扩写后确实变长了
        if len(expanded) > len(content) + 100:
            cur.execute(
                "UPDATE skills SET content = ? WHERE id = ?",
                (expanded, skill_id)
            )
            updated += 1
    
    conn.commit()
    
    # 验证结果
    cur.execute("SELECT COUNT(*) FROM skills WHERE length(content) < 400")
    remaining_short = cur.fetchone()[0]
    
    cur.execute("SELECT AVG(length(content)) FROM skills")
    avg_len = cur.fetchone()[0]
    
    cur.execute("""
        SELECT 
            CASE 
                WHEN length(content) < 200 THEN '<200字'
                WHEN length(content) < 400 THEN '200-400字'
                WHEN length(content) < 800 THEN '400-800字'
                ELSE '800字+'
            END as quality,
            COUNT(*) as cnt
        FROM skills
        GROUP BY quality
        ORDER BY MIN(length(content))
    """)
    
    print(f"\n扩写完成: {updated} 条")
    print(f"仍<400字: {remaining_short} 条")
    print(f"平均内容长度: {avg_len:.0f} 字")
    print(f"\n新分布:")
    for r in cur.fetchall():
        print(f"  {r[0]}: {r[1]} 条")
    
    conn.close()


if __name__ == "__main__":
    main()
