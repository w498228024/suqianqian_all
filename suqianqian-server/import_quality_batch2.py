def main():
    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()

    cur.execute("SELECT title FROM skills")
    existing = set(r[0] for r in cur.fetchall())

    cur.execute("SELECT COUNT(*) FROM skills")
    total_before = cur.fetchone()[0]

    now = datetime.now().isoformat()
    count = 0

    for skill in SKILLS:
        if skill["title"] in existing:
            continue
        cur.execute("""
            INSERT INTO skills (title, desc, content, category, sub_category, tags, fit_tools,
                              source_type, license, status, created_at, updated_at)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, 'published', ?, ?)
        """, (
            skill["title"], skill["desc"], skill["content"],
            skill["category"], skill["sub_category"],
            json.dumps(skill["tags"], ensure_ascii=False),
            json.dumps(["其他"], ensure_ascii=False),
            "原创精选", "CC-BY-4.0", now, now
        ))
        existing.add(skill["title"])
        count += 1

    conn.commit()

    cur.execute("SELECT COUNT(*) FROM skills")
    total_after = cur.fetchone()[0]

    print(f"新增: {count} 条")
    print(f"总数: {total_before} -> {total_after}")
    print(f"还差: {1000 - total_after} 条")

    conn.close()

if __name__ == "__main__":
    main()
