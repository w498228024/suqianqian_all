def upgrade_skill(content, category):
    """为 Skill 补充缺失的结构化要素"""
    upgrades = CATEGORY_UPGRADES.get(category, DEFAULT_UPGRADE)
    
    # 检查是否已有相关内容
    has_rules = any(kw in content for kw in ['规则', '限制', '注意', '不要', '禁止', '不能'])
    has_output = any(kw in content for kw in ['输出格式', '回复格式', '输出标准'])
    has_example = any(kw in content for kw in ['示例', '例如', '例：', '模板'])
    
    additions = []
    
    # 补充规则（如果没有或者很弱）
    if not has_rules or len(content) < 300:
        additions.append(upgrades["rules"])
    
    # 补充输出格式
    if not has_output:
        additions.append(upgrades["output"])
    
    # 补充示例
    if not has_example:
        additions.append(upgrades["example"])
    
    if additions:
        return content.rstrip() + "\n\n" + "\n\n".join(additions)
    return content


def main():
    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()
    
    cur.execute("SELECT id, content, category FROM skills")
    rows = cur.fetchall()
    
    print(f"处理 {len(rows)} 条 Skill...")
    
    upgraded = 0
    for sid, content, category in rows:
        new_content = upgrade_skill(content or "", category)
        if len(new_content) > len(content or ""):
            cur.execute("UPDATE skills SET content = ? WHERE id = ?", (new_content, sid))
            upgraded += 1
    
    conn.commit()
    
    # 验证
    cur.execute("SELECT AVG(length(content)) FROM skills")
    avg_len = cur.fetchone()[0]
    
    cur.execute("SELECT COUNT(*) FROM skills WHERE length(content) >= 500")
    long_count = cur.fetchone()[0]
    
    cur.execute("SELECT COUNT(*) FROM skills WHERE length(content) < 300")
    short_count = cur.fetchone()[0]
    
    print(f"\n升级完成: {upgraded} 条")
    print(f"平均长度: {avg_len:.0f} 字")
    print(f">=500字: {long_count} 条")
    print(f"<300字: {short_count} 条")
    
    conn.close()


if __name__ == "__main__":
    main()
