def main():
    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()

    # 获取已有标题
    cur.execute("SELECT title FROM skills")
    existing = set(r[0] for r in cur.fetchall())
    before = len(existing)

    now = datetime.now().isoformat()
    count = 0

    for skill in INDUSTRY_SKILLS:
        if skill["title"] in existing:
            continue

        cur.execute("""
            INSERT INTO skills (title, desc, content, category, sub_category, tags, fit_tools,
                              source_type, license, status, created_at, updated_at)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, 'published', ?, ?)
        """, (
            skill["title"],
            skill["desc"],
            skill["content"],
            skill["category"],
            skill.get("sub_category", ""),
            json.dumps(skill.get("tags", []), ensure_ascii=False),
            json.dumps(skill.get("fit_tools", ["其他"]), ensure_ascii=False),
            "开源改编",
            "CC-BY-4.0",
            now, now
        ))
        existing.add(skill["title"])
        count += 1

    conn.commit()

    # 统计
    cur.execute("SELECT COUNT(*) FROM skills")
    after = cur.fetchone()[0]

    print(f"新增行业 Skill: {count} 条")
    print(f"总数: {before} → {after}")

    # 分类统计
    cur.execute("SELECT category, COUNT(*) as cnt FROM skills GROUP BY category ORDER BY cnt DESC")
    print(f"\n分类分布:")
    for row in cur.fetchall():
        print(f"  {row[0]}: {row[1]} 条")

    conn.close()


if __name__ == "__main__":
    main()
