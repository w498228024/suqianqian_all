def classify_skill(title, content, current_category):
    """根据标题和内容匹配新分类"""
    text = (title + " " + (content or "")[:500]).lower()

    for category, sub_category, keywords in CATEGORY_MAP:
        for kw in keywords:
            if kw.lower() in text:
                return category, sub_category

    # 如果没匹配到，保留原分类，sub_category 设为"其他"
    return current_category, "其他"


def main():
    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()

    cur.execute("SELECT id, title, content, category FROM skills")
    rows = cur.fetchall()

    stats = {}
    updated = 0

    for skill_id, title, content, old_cat in rows:
        new_cat, new_sub = classify_skill(title, content, old_cat)

        cur.execute(
            "UPDATE skills SET category = ?, sub_category = ? WHERE id = ?",
            (new_cat, new_sub, skill_id)
        )

        key = f"{new_cat}|||{new_sub}"
        stats[key] = stats.get(key, 0) + 1
        updated += 1

    conn.commit()

    # 打印新分类分布
    print(f"已更新 {updated} 条 Skill 的分类\n")
    print("=== 新分类分布 ===")

    # 按大类分组
    by_category = {}
    for key, count in sorted(stats.items()):
        cat, sub = key.split("|||", 1)
        if cat not in by_category:
            by_category[cat] = {}
        by_category[cat][sub] = count

    total = 0
    for cat in sorted(by_category.keys()):
        cat_total = sum(by_category[cat].values())
        total += cat_total
        print(f"\n【{cat}】({cat_total} 条)")
        for sub, count in sorted(by_category[cat].items(), key=lambda x: -x[1]):
            print(f"  ├─ {sub}: {count} 条")

    print(f"\n总计: {total} 条")
    conn.close()


if __name__ == "__main__":
    main()
